-- V39: AI related tables and legacy experiment compatibility table.
-- This migration is intentionally idempotent because some cloud databases may
-- already contain part of these tables from manual imports or failed attempts.

CREATE TABLE IF NOT EXISTS `ai_remarks` (
    `student_id` VARCHAR(50) NOT NULL COMMENT 'Student number',
    `student_name` VARCHAR(50) COMMENT 'Student name',
    `experiment_id` INT NOT NULL COMMENT 'Experiment ID',
    `experiment_name` VARCHAR(200) COMMENT 'Experiment name',
    `airemark` LONGTEXT COMMENT 'AI generated remark',
    PRIMARY KEY (`student_id`, `experiment_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI remarks';

CREATE TABLE IF NOT EXISTS `ai_suggested_problems` (
    `student_id` VARCHAR(50) NOT NULL COMMENT 'Student number',
    `student_name` VARCHAR(50) COMMENT 'Student name',
    `experiment_id` INT NOT NULL COMMENT 'Experiment ID',
    `suggested_problems` LONGTEXT COMMENT 'AI suggested problems',
    PRIMARY KEY (`student_id`, `experiment_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI suggested problems';

CREATE TABLE IF NOT EXISTS `experiment` (
    `experiment_id` INT AUTO_INCREMENT PRIMARY KEY,
    `num` INT COMMENT 'Experiment number',
    `name` VARCHAR(200) NOT NULL COMMENT 'Experiment name',
    `deadline` DATETIME COMMENT 'Deadline',
    `describe` TEXT COMMENT 'Description',
    `requirements` TEXT COMMENT 'Requirements',
    `topic_sum` INT DEFAULT 0 COMMENT 'Problem count',
    `teacher_id` VARCHAR(50) COMMENT 'Teacher ID',
    `class` VARCHAR(128) DEFAULT NULL COMMENT 'Class name',
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Experiment';

CREATE TABLE IF NOT EXISTS `ai_error_analysis_report` (
    `id` BIGINT NOT NULL AUTO_INCREMENT,
    `analysis_id` VARCHAR(64) NOT NULL COMMENT 'Analysis ID',
    `student_no` VARCHAR(32) NOT NULL COMMENT 'Student number',
    `experiment_id` INT NOT NULL COMMENT 'Experiment ID',
    `experiment_name` VARCHAR(256) DEFAULT '' COMMENT 'Experiment name',
    `report_type` VARCHAR(32) NOT NULL COMMENT 'Report type',
    `severity` VARCHAR(16) DEFAULT 'MEDIUM' COMMENT 'Severity',
    `ai_generated` TINYINT(1) NOT NULL DEFAULT 1 COMMENT 'Generated by AI',
    `overall_assessment` TEXT COMMENT 'Overall assessment',
    `error_categories_json` JSON COMMENT 'Error categories JSON',
    `learning_suggestions_json` JSON COMMENT 'Learning suggestions JSON',
    `weak_points_json` JSON COMMENT 'Weak points JSON',
    `study_plan_json` JSON COMMENT 'Study plan JSON',
    `recommended_problems_json` JSON COMMENT 'Recommended problems JSON',
    `summary_message` TEXT COMMENT 'Summary message',
    `warning_type` VARCHAR(32) DEFAULT NULL COMMENT 'Warning type',
    `warning_message` TEXT COMMENT 'Warning message',
    `teacher_note` TEXT COMMENT 'Teacher note',
    `intervention_triggered` TINYINT(1) DEFAULT 0 COMMENT 'Intervention triggered',
    `raw_response_json` JSON COMMENT 'Raw response JSON',
    `created_at` TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at` TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_analysis_id` (`analysis_id`),
    KEY `idx_student_exp` (`student_no`, `experiment_id`),
    KEY `idx_student_exp_type` (`student_no`, `experiment_id`, `report_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI error analysis report';
